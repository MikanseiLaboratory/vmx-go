func GolombCodeLength(input uint32) uint32 {
	if int(input) >= len(GolombLengthLUT) {
		return uint32(32-leadingZeros32(input))*2 - 1
	}
	return uint32(GolombLengthLUT[input])
}

func leadingZeros32(x uint32) int {
	if x == 0 {
		return 32
	}
	n := 0
	for x&0x80000000 == 0 {
		n++
		x <<= 1
	}
	return n
}

func SelectRGBYUV(cs int, height int) *[3]ShortRGB {
	switch cs {
	case 601:
		return &RGBYUV601
	case 709:
		return &RGBYUV709
	default:
		if height >= 720 {
			return &RGBYUV709
		}
		return &RGBYUV601
	}
}

